function sub(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Look up `key` for `lang`, falling back to English for an unknown language or a
 * key missing from that language's table, then substitute `{var}` placeholders. */
export function t(lang: string | undefined | null, key: string, vars?: Vars): string {
  const l = langOf(lang);
  const raw = TABLE[l][key] ?? TABLE.en[key] ?? key;
  return sub(raw, vars);
}

/** The 11 language codes this bot ships, in table order. */
export const APP_LANGS: Lang[] = [...LANGS];

/** Every `app_*` key, for every language, as a plain object — the Mini App's embedded
 * `APP_I18N` dictionary. English fills any gap so a client lookup can never miss.
 * Both loops are bounded by the static table (11 languages x the app_* key set). */
export function appDict(): Record<string, Record<string, string>> {
  const keys = Object.keys(TABLE.en).filter((k) => k.startsWith("app_"));
  const out: Record<string, Record<string, string>> = {};
  for (const l of LANGS) {
    const m: Record<string, string> = {};
    for (const k of keys) m[k] = TABLE[l][k] ?? TABLE.en[k];
    out[l] = m;
  }
  return out;
}
